import yfinance as yf
import pandas as pd
from datetime import timezone

import sys

ticker = sys.argv[1] if len(sys.argv) > 1 else 'USDJPY'
yf_symbol = 'JPY=X' if ticker == 'USDJPY' else f"{ticker}=X"

print(f"Fetching 730 days of 1H data from Yahoo Finance for {yf_symbol}...")
df_1h = yf.download(yf_symbol, interval="1h", period="730d")

if df_1h.empty:
    print("Failed to fetch data.")
else:
    # yfinance multi-index columns can be tricky, let's flatten if needed
    if isinstance(df_1h.columns, pd.MultiIndex):
        df_1h.columns = [col[0] for col in df_1h.columns]
        
    df_1h = df_1h.reset_index()
    
    # Rename columns to match what the pipeline expects
    # 'Datetime' or 'index' -> 'Time'
    time_col = 'Datetime' if 'Datetime' in df_1h.columns else 'Date' if 'Date' in df_1h.columns else df_1h.columns[0]
    
    df_1h = df_1h.rename(columns={time_col: 'Time'})
    
    # Ensure UTC timezone
    df_1h['Time'] = pd.to_datetime(df_1h['Time'], utc=True)
    
    df_1h.set_index('Time', inplace=True)
    
    # Resample to 4H
    print("Resampling to H4...")
    df_h4 = df_1h.resample('4h').agg({
        'Open': 'first',
        'High': 'max',
        'Low': 'min',
        'Close': 'last',
        'Volume': 'sum'
    }).dropna()
    
    df_h4 = df_h4.reset_index()
    
    # The pipeline expects 'Weekend_Gap' to exist, but it's generated by older scripts or can be ignored by v3.
    # Feature engineering V3 only uses Time, Open, High, Low, Close, Volume.
    out_csv = f"{ticker}_H4.csv"
    df_h4.to_csv(out_csv, index=False)
    print(f"Saved {len(df_h4)} real {ticker} H4 candles to {out_csv}.")
